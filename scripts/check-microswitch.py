"""Check the received KW11-3Z reference meshes against recorded dimensions.

Requires the pinned OpenSCAD and the booklet Python dependencies. Outputs stay
under hardware/generated by default. These are CAD checks, not physical tests.
"""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path

import manifold3d as mf
import numpy as np
import trimesh

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'hardware/assemblies/winch/roller-lever-microswitch.scad'


def manifold(mesh):
    return mf.Manifold(mf.Mesh(np.asarray(mesh.vertices, dtype=np.float32),
                               np.asarray(mesh.faces, dtype=np.uint32)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'hardware/generated/kw11-3z-check')
    args = parser.parse_args()
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=True)
    registry = json.loads((ROOT / 'hardware/models.json').read_text())
    version = subprocess.run(['openscad', '--version'], capture_output=True, text=True, check=True)
    assert (version.stdout + version.stderr).strip() == 'OpenSCAD version ' + registry['openScadVersion']
    meshes = {}

    def export(name, pose='released', part='all'):
        target = out / (name + '.stl')
        result = subprocess.run(['openscad', '-o', str(target), '-D', f'pose="{pose}"',
                                 '-D', f'part="{part}"', str(SOURCE)],
                                capture_output=True, text=True, timeout=120)
        assert result.returncode == 0 and not any(s in result.stderr for s in ['WARNING:', 'ERROR:']), result.stderr
        mesh = trimesh.load_mesh(target)
        assert mesh.is_watertight and mesh.is_winding_consistent and mesh.volume > 0, name
        meshes[name] = {'bounds_mm': mesh.bounds.tolist(), 'triangles': len(mesh.faces),
                        'stl_sha256': hashlib.sha256(target.read_bytes()).hexdigest()}
        print('Checked', name, flush=True)
        return mesh

    case = export('case', part='case')
    assert np.allclose(case.bounds, [[0, -3.35, 0], [20, 3.35, 10.7]], atol=0.003), case.bounds
    solid = manifold(case)
    holes = []
    for x in [5.5, 15.0]:
        # A 2.4 mm through-probe must clear each recorded 2.5 mm bore.
        probe = trimesh.creation.cylinder(radius=1.2, height=8, sections=96)
        probe.apply_transform(trimesh.transformations.rotation_matrix(np.pi / 2, [1, 0, 0]))
        probe.apply_translation([x, 0, 2.8])
        clear = float((solid ^ manifold(probe)).volume())
        assert clear < 0.005, (x, clear)
        # A displaced mount must be detected, rather than merely compiling.
        probe.apply_translation([0.5, 0, 0])
        shifted = float((solid ^ manifold(probe)).volume())
        assert shifted > 0.1, (x, shifted)
        holes.append({'centre_xz_mm': [x, 2.8], 'probe_diameter_mm': 2.4,
                      'intersection_mm3': clear, 'shifted_0_5_mm_intersection_mm3': shifted})

    poses = {}
    for state, expected in [('released', 21.0), ('clicked', 18.0), ('fully-pressed', 16.0)]:
        roller = export(state + '-roller', pose=state, part='roller')
        full = export(state, pose=state)
        assert np.allclose(roller.extents, [4.8, 4.0, 4.8], atol=0.003), roller.extents
        assert abs(roller.bounds[1, 2] - expected) < 0.003, roller.bounds
        assert abs(full.bounds[1, 2] - expected) < 0.003, full.bounds
        assert abs(full.bounds[0, 2] + 3.3) < 0.003, full.bounds
        assert abs(full.extents[1] - 7.2) < 0.003, full.extents
        poses[state] = {'recorded_roller_top_mm': expected,
                        'mesh_roller_top_mm': float(roller.bounds[1, 2]),
                        'full_bounds_mm': full.bounds.tolist(),
                        'watertight_components': int(full.body_count)}

    sources = [SOURCE, ROOT / 'hardware/lib/arbi.scad', ROOT / 'hardware/models.json', Path(__file__).resolve()]
    model = next(m for m in registry['models'] if m['id'] == 'roller-lever-microswitch')
    report = {'status': 'nominal CAD only', 'model_revision': model['revision'],
              'source_hashes': {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sources},
              'meshes': meshes, 'hole_probes': holes, 'poses': poses,
              'limits': 'Owner/drawing dimensions. Lever attachment, horizontal positions and motion path remain approximate. No rated overtravel or physical fit acceptance.'}
    (out / 'check.json').write_text(json.dumps(report, indent=2) + '\n')
    print('PASS case, two through-bores, displaced-mount controls, roller dimensions and three pose heights.', flush=True)


if __name__ == '__main__':
    main()
